"""Analytic and synthetic fixtures with no external media dependency."""

from __future__ import annotations

from typing import Mapping, Optional, Tuple, Union

import numpy as np

from .arrays import PlanarFrame, frame_sha256
from .degradation import apply_degradation


def step_fixture(size: int, orientation: str, offset: float = 0.0) -> np.ndarray:
    if size < 8:
        raise ValueError("step fixture size must be at least eight")
    yy, xx = np.indices((size, size), dtype=np.float64)
    center = (size - 1) / 2.0 + offset
    if orientation == "vertical":
        signed = xx - center
    elif orientation == "horizontal":
        signed = yy - center
    elif orientation == "diagonal":
        signed = (xx + yy) / np.sqrt(2.0) - center * np.sqrt(2.0)
    else:
        raise ValueError("unsupported step orientation")
    return (signed >= 0.0).astype(np.float64)


def impulse_fixture(size: int = 33) -> Tuple[np.ndarray, np.ndarray]:
    reference = np.zeros((size, size), dtype=np.float64)
    center = size // 2
    reference[center, center] = 1.0
    support = np.zeros_like(reference, dtype=bool)
    support[center, center] = True
    return reference, support


def thin_line_fixture(size: int = 33) -> Tuple[np.ndarray, np.ndarray]:
    reference = np.zeros((size, size), dtype=np.float64)
    support = np.zeros_like(reference, dtype=bool)
    support[:, size // 2] = True
    reference[support] = 1.0
    return reference, support


def locked_analytic_fixture_frames(
    definition: Mapping[str, object],
    degradation_policy: Mapping[str, object],
) -> Tuple[PlanarFrame, PlanarFrame, Optional[np.ndarray]]:
    """Reconstruct one v2 analytic target and its exact pre-420 degradation."""

    geometry = definition.get("target_geometry")
    generator = definition.get("generator")
    if (
        not isinstance(geometry, dict)
        or not isinstance(generator, dict)
        or not isinstance(generator.get("parameters"), dict)
    ):
        raise ValueError("analytic fixture geometry or generator is absent")
    y_shape = tuple(int(value) for value in geometry["y"])
    cb_shape = tuple(int(value) for value in geometry["cb"])
    parameters = generator["parameters"]
    neutral = np.zeros(cb_shape, dtype=np.float64)
    support: Optional[np.ndarray] = None
    generator_id = generator.get("id")
    if generator_id == "unit-step":
        y = step_fixture(
            y_shape[0],
            str(parameters["orientation"]),
            offset=float(parameters["offset"]),
        )
        cb = neutral
        cr = neutral
    elif generator_id == "single-unit-impulse":
        y = np.full(y_shape, float(parameters["background"]), dtype=np.float64)
        row, column = parameters["row_column"]
        y[int(row), int(column)] = float(parameters["value"])
        support = np.zeros(y_shape, dtype=bool)
        support[int(row), int(column)] = True
        cb = neutral
        cr = neutral
    elif generator_id == "vertical-unit-thin-line":
        y = np.full(y_shape, float(parameters["background"]), dtype=np.float64)
        support = np.zeros(y_shape, dtype=bool)
        support[:, int(parameters["column"])] = True
        y[support] = float(parameters["value"])
        cb = neutral
        cr = neutral
    elif generator_id == "normalized-nyquist-checker":
        yy, xx = np.indices(y_shape, dtype=np.float64)
        y = 0.5 + 0.5 * ((-1.0) ** (yy + xx))
        support = np.zeros(y_shape, dtype=bool)
        row, column = definition["measurement_support"]["true_coordinates"][0]
        support[int(row), int(column)] = True
        cb = neutral
        cr = neutral
    elif generator_id == "left-sited-centered-chroma-step":
        _, xx = np.indices(y_shape)
        y = (xx >= int(parameters["luma_edge_column"])).astype(np.float64)
        _, cx = np.indices(cb_shape)
        cb = (cx >= int(parameters["chroma_edge_column"])).astype(np.float64) - 0.5
        cr = cb.copy()
    else:
        raise ValueError("unsupported analytic fixture generator")
    target = PlanarFrame(y=y, cb=cb, cr=cr)
    profiles = degradation_policy.get("profiles")
    if not isinstance(profiles, list):
        raise ValueError("analytic fixture degradation profiles are absent")
    matching = [
        profile
        for profile in profiles
        if isinstance(profile, dict)
        and profile.get("id") == definition.get("degradation_profile_id")
    ]
    if len(matching) != 1:
        raise ValueError("analytic fixture degradation profile is absent or duplicated")
    degraded = apply_degradation(target, matching[0])
    if (
        frame_sha256(target) != definition.get("target_reference_frame_sha256")
        or frame_sha256(degraded) != definition.get("low_resolution_frame_sha256")
    ):
        raise ValueError("analytic fixture generated bytes differ from the manifest")
    return target, degraded, support


def synthetic_planar_frame(
    index: int,
    size: Union[int, Tuple[int, int]] = 64,
) -> PlanarFrame:
    height, width = (size, size) if isinstance(size, int) else size
    if min(height, width) < 32 or height % 2 != 0 or width % 2 != 0:
        raise ValueError("synthetic frame dimensions must be even and at least 32")
    yy, xx = np.indices((height, width), dtype=np.float64)
    ramp = xx / (width - 1)
    vertical = (xx >= width / 2 + index).astype(np.float64)
    diagonal = ((xx + yy + index) % 16 < 8).astype(np.float64)
    y = np.clip(0.45 * ramp + 0.35 * vertical + 0.20 * diagonal, 0.0, 1.0)

    chroma_height = height // 2
    chroma_width = width // 2
    cy, cx = np.indices((chroma_height, chroma_width), dtype=np.float64)
    cb = np.where(cx >= chroma_width / 2, 0.30, -0.30)
    cr = 0.25 * np.sin((cx + cy + index) * 2.0 * np.pi / 16.0)
    return PlanarFrame(y=y, cb=cb, cr=cr)
